function getFontCacheKey(path: string): string {
  try {
    return new URL(path, window.location.origin).href;
  } catch {
    return path;
  }
}

function getPathTransition(index: number, duration: number, delay: number) {
  const pathDelay = delay + index * PATH_DELAY_STEP;

  return {
    pathLength: {
      delay: pathDelay,
      duration,
      ease: 'easeInOut' as const,
    },
    opacity: {
      delay: pathDelay + OPACITY_DELAY_OFFSET,
      duration: 0.01,
    },
  };
}

async function loadFontFromPaths(fontPaths: string[]): Promise<SignatureFont> {
  for (const path of fontPaths) {
    try {
      const cacheKey = getFontCacheKey(path);
      const cachedFont = fontCache.get(cacheKey);

      if (cachedFont) {
        return cachedFont;
      }

      const response = await fetch(path);

      if (!response.ok) {
        continue;
      }

      const fontBuffer = await response.arrayBuffer();
      const font = parseFont(fontBuffer) as unknown as SignatureFont;
      fontCache.set(cacheKey, font);

      return font;
    } catch {
      // Try next path
    }
  }

  throw new Error(
    `Font could not be loaded from the provided path${fontPaths.length === 1 ? '' : 's'}: ${fontPaths.join(', ')}`,
  );
}

async function buildSignaturePaths({
  text,
  fontSize,
  baseline,
  horizontalPadding,
}: {
  text: string;
  fontSize: number;
  baseline: number;
  horizontalPadding: number;
}): Promise<{ paths: string[]; width: number }> {
  const font = await loadFontFromPaths(['/LastoriaBoldRegular.otf']);

  let x = horizontalPadding;
  const nextPaths: string[] = [];

  for (const char of text) {
    const glyph = font.charToGlyph(char);
    const path = glyph.getPath(x, baseline, fontSize);
    nextPaths.push(path.toPathData(2));

    const advanceWidth = glyph.advanceWidth ?? font.unitsPerEm;
    x += advanceWidth * (fontSize / font.unitsPerEm);
  }

  return {
    paths: nextPaths,
    width: Math.round(x + horizontalPadding),
  };
}

function renderMotionPaths({
  paths,
  stroke,
  strokeWidth,
  strokeLinecap,
  strokeLinejoin,
  duration,
  delay,
}: {
  paths: string[];
  stroke: string;
  strokeWidth: number;
  strokeLinecap: 'round' | 'butt';
  strokeLinejoin: 'round';
  duration: number;
  delay: number;
}) {
  return paths.map((d, index) => {
    if (!d) return null;
    return (
      <motion.path
        key={index}
        d={d}
        stroke={stroke}
        strokeWidth={strokeWidth}
        fill="none"
        variants={PATH_VARIANTS}
        transition={getPathTransition(index, duration, delay)}
        vectorEffect="non-scaling-stroke"
        strokeLinecap={strokeLinecap}
        strokeLinejoin={strokeLinejoin}
      />
    );
  });
}

const PATH_VARIANTS = {
  hidden: { pathLength: 0, opacity: 0 },
  visible: { pathLength: 1, opacity: 1 },
};

